"use client";

import { useEffect, useState } from 'react';
import { twinsApi, predictiveApi, entityApi } from '@/lib/api';

import AppShell from '@/components/layout/AppShell';
import { useDialog } from '@/context/DialogContext';

export default function DigitalTwinsCenter() {
  const { showToast } = useDialog();
  const [twins, setTwins] = useState<any[]>([]);
  const [forecasts, setForecasts] = useState<any[]>([]);
  const [risks, setRisks] = useState<any[]>([]);
  const [loading, setLoading] = useState(true);

  // Create Twin Modal State
  const [isCreateModalOpen, setIsCreateModalOpen] = useState(false);
  const [entities, setEntities] = useState<any[]>([]);
  const [selectedEntityId, setSelectedEntityId] = useState("");
  const [creating, setCreating] = useState(false);

  useEffect(() => {
    const loadData = async () => {
      try {
        const [twinsRes, forecastsRes, risksRes] = await Promise.all([
          twinsApi.list({ timestamp: new Date().getTime() }),
          predictiveApi.getForecasts(),
          predictiveApi.getRisks(),
        ]);
        setTwins(twinsRes.data);
        setForecasts(forecastsRes.data);
        setRisks(risksRes.data);
      } catch (error) {
        console.error("Failed to load digital twins center data:", error);
      } finally {
        setLoading(false);
      }
    };
    loadData();
  }, []);

  const handleOpenCreateModal = async () => {
    setIsCreateModalOpen(true);
    try {
      const res = await entityApi.list();
      setEntities(res.data.items || []);
    } catch (e) {
      console.error("Failed to load entities for twin creation:", e);
    }
  };

  const handleCreateTwin = async () => {
    if (!selectedEntityId) return;
    setCreating(true);
    try {
      // Find the entity locally (converting ID to string for comparison if necessary)
      const entity = entities.find(e => String(e.id) === selectedEntityId);
      if (!entity) return;
      
      await twinsApi.create({
        name: entity.name,
        description: entity.description || `Digital Twin of ${entity.name}`,
        domain: entity.type || "General",
        parameters: entity.properties || {}
      });
      
      setIsCreateModalOpen(false);
      // Reload twins
      const twinsRes = await twinsApi.list({ timestamp: new Date().getTime() });
      setTwins(twinsRes.data);
    } catch (e) {
      console.error("Failed to create twin:", e);
      showToast("Failed to create twin. Check console.", "error");
    } finally {
      setCreating(false);
    }
  };

  if (loading) {
    return (
      <AppShell>
        <div className="p-8 text-white">Loading Digital Twin Center...</div>
      </AppShell>
    );
  }

  return (
    <AppShell>
      <div className="p-8 space-y-8 min-h-screen text-white relative">
        <header>
          <h1 className="text-3xl font-bold bg-clip-text text-transparent bg-gradient-to-r from-accent to-accent-secondary">
            Digital Twin Center
          </h1>
          <p className="text-gray-400 mt-2">Operational Intelligence and Predictive Forecasting</p>
        </header>

        {/* Disclaimers Area */}
        <div className="bg-yellow-900/30 border border-yellow-700/50 rounded-lg p-4 mb-8">
          <h3 className="text-yellow-500 font-bold flex items-center">
            <svg className="w-5 h-5 mr-2" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M12 9v2m0 4h.01m-6.938 4h13.856c1.54 0 2.502-1.667 1.732-3L13.732 4c-.77-1.333-2.694-1.333-3.464 0L3.34 16c-.77 1.333.192 3 1.732 3z" /></svg>
            CRITICAL DISCLAIMER
          </h3>
          <p className="text-yellow-200/80 mt-1 text-sm">
            Predictions generated by the Unified Future Modeling Engine must never be presented as facts. Every forecast displayed below represents an estimate based on current knowledge graph connections. 
            Models include assumptions, supporting evidence, and confidence scores. They are estimates, not absolute truths.
          </p>
        </div>

        <div className="grid grid-cols-1 lg:grid-cols-3 gap-6">
          
          {/* Twins Column */}
          <div className="space-y-4">
            <div className="flex justify-between items-center border-b border-white/10 pb-2">
              <h2 className="text-xl font-semibold">Active Twins</h2>
              <button 
                onClick={handleOpenCreateModal}
                className="text-xs bg-accent/20 text-accent hover:bg-accent/40 px-3 py-1 rounded transition-colors"
              >
                + Create Twin
              </button>
            </div>
            {twins.length === 0 ? (
              <div className="bg-white/5 rounded-lg p-4 text-gray-500 text-sm">No Active Twins</div>
            ) : (
              twins.map(twin => (
                <div key={twin.id} className="bg-white/5 border border-white/10 rounded-lg p-4 hover:border-accent/50 transition-colors">
                  <div className="flex justify-between items-start">
                    <h3 className="font-semibold text-accent-hover">{twin.name}</h3>
                    <span className={`px-2 py-1 text-xs rounded-full ${twin.health_score > 0.8 ? 'bg-green-900/50 text-green-300' : 'bg-red-900/50 text-red-300'}`}>
                      Health: {(twin.health_score * 100).toFixed(0)}%
                    </span>
                  </div>
                  <p className="text-sm text-gray-400 mt-2">{twin.description}</p>
                  <div className="mt-4 pt-4 border-t border-white/10 flex justify-end space-x-2">
                     <a href={`/digital-twins/${twin.id}/optimize`} className="text-xs bg-accent-secondary/50 hover:bg-accent-secondary text-white px-3 py-1.5 rounded transition-colors border border-accent-secondary/30">
                       Optimize Goal
                     </a>
                     <a href={`/digital-twins/${twin.id}/simulate`} className="text-xs bg-accent hover:bg-accent-hover px-3 py-1.5 rounded transition-colors">
                       Run Simulation
                     </a>
                  </div>
                </div>
              ))
            )}
          </div>

          {/* Forecasts Column */}
          <div className="space-y-4 lg:col-span-2">
            <h2 className="text-xl font-semibold border-b border-white/10 pb-2">System Forecasts</h2>
            {forecasts.length === 0 ? (
              <div className="bg-white/5 rounded-lg p-4 text-gray-500 text-sm">No Active Forecasts</div>
            ) : (
              forecasts.map(forecast => (
                <div key={forecast.id} className="bg-accent-secondary/5 border border-accent-secondary/20 rounded-lg p-5">
                  <div className="flex justify-between items-start mb-3">
                    <div>
                      <h3 className="font-semibold text-lg">{forecast.target_metric}</h3>
                      <p className="text-accent text-xl font-bold mt-1">{forecast.predicted_value}</p>
                    </div>
                    <div className="text-right">
                      <div className="text-sm text-gray-400">Timeframe: {forecast.timeframe_days} Days</div>
                      <div className="text-sm mt-1">Confidence: <span className="text-white">{(forecast.confidence * 100).toFixed(1)}%</span></div>
                    </div>
                  </div>
                  
                  <div className="grid grid-cols-2 gap-4 mt-4 text-sm">
                    <div className="bg-black/30 p-3 rounded">
                      <h4 className="text-gray-400 font-medium mb-1">Assumptions</h4>
                      <ul className="list-disc pl-4 space-y-1 text-gray-300">
                        {forecast.assumptions.map((a: string, i: number) => <li key={i}>{a}</li>)}
                      </ul>
                    </div>
                    <div className="bg-black/30 p-3 rounded">
                      <h4 className="text-gray-400 font-medium mb-1">Evidence</h4>
                      <ul className="list-disc pl-4 space-y-1 text-gray-300">
                        {forecast.evidence.map((e: string, i: number) => <li key={i}>{e}</li>)}
                      </ul>
                    </div>
                  </div>
                  
                  <div className="mt-3 text-xs text-gray-500 flex justify-between items-center">
                    <span>Data Coverage: {(forecast.data_coverage * 100).toFixed(1)}%</span>
                    <span className="text-yellow-600/80 italic">{forecast.disclaimer}</span>
                  </div>
                </div>
              ))
            )}
          </div>
        </div>

        {/* Create Twin Modal */}
        {isCreateModalOpen && (
          <div className="fixed inset-0 bg-black/80 flex items-center justify-center z-50">
            <div className="bg-bg-elevated border border-accent/30 rounded-lg p-6 w-[500px] max-w-full">
              <h2 className="text-xl font-bold mb-4">Create Digital Twin</h2>
              <p className="text-sm text-gray-400 mb-6">Select an entity from the Knowledge Graph to mirror as a Digital Twin.</p>
              
              <div className="space-y-4">
                <div>
                  <label className="block text-sm font-medium text-gray-300 mb-2">Select Entity</label>
                  <select 
                    value={selectedEntityId} 
                    onChange={e => setSelectedEntityId(e.target.value)}
                    className="w-full bg-black/50 border border-white/20 rounded p-3 text-white focus:outline-none focus:border-accent"
                  >
                    <option value="" disabled>-- Choose an entity --</option>
                    {entities.map(e => (
                      <option key={e.id} value={e.id}>{e.name} ({e.type})</option>
                    ))}
                  </select>
                </div>
                
                <div className="flex justify-end space-x-3 mt-8">
                  <button 
                    onClick={() => setIsCreateModalOpen(false)}
                    className="px-4 py-2 rounded text-gray-400 hover:text-white transition-colors"
                  >
                    Cancel
                  </button>
                  <button 
                    onClick={handleCreateTwin}
                    disabled={!selectedEntityId || creating}
                    className={`px-6 py-2 rounded font-medium transition-colors ${!selectedEntityId || creating ? 'bg-accent/50 cursor-not-allowed' : 'bg-accent hover:bg-accent-hover text-white'}`}
                  >
                    {creating ? 'Initializing Twin...' : 'Create Twin'}
                  </button>
                </div>
              </div>
            </div>
          </div>
        )}

      </div>
    </AppShell>
  );
}
