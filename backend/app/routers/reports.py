from app.utils.rbac import get_room_membership, RequireRole, require_room_admin
from app.models.multi_tenant import RoomMembership
from fastapi import APIRouter, Depends
from sqlalchemy.ext.asyncio import AsyncSession
from fastapi.responses import PlainTextResponse
from app.database import get_db
from app.routers.auth import get_current_user
from app.models.user import User
from app.neo4j_driver import get_neo4j_driver
from datetime import datetime

router = APIRouter()

@router.get("/markdown", response_class=PlainTextResponse)
async def generate_markdown_report(membership: RoomMembership = Depends(get_room_membership), db: AsyncSession = Depends(get_db)):
    driver = get_neo4j_driver()
    if not driver:
        return "# Intelligence Report\n\nDatabase not connected."
        
    date_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    md = f"# Research Intelligence Report\n\n"
    md += f"**Generated By:** {membership.user.name}\n"
    md += f"**Date:** {date_str}\n\n"
    
    with driver.session() as session:
        # 1. Global Stats
        stats = session.run("MATCH (e:Entity {room_id: $room_id}) RETURN count(e) as c", room_id=membership.room_id).single()
        rel_stats = session.run("MATCH (s:Entity {room_id: $room_id})-[r]->(t:Entity {room_id: $room_id}) RETURN count(r) as c", room_id=membership.room_id).single()
        md += "## 1. Graph Statistics\n"
        md += f"- **Total Entities Captured:** {stats['c']}\n"
        md += f"- **Total Relationships Discovered:** {rel_stats['c']}\n\n"
        
        # 2. Contradictions
        md += "## 2. Active Contradictions\n"
        contra = session.run("""
        MATCH (s:Entity {room_id: $room_id})-[r1:CONTRADICTS]->(t:Entity {room_id: $room_id})
        RETURN s.name as source, t.name as target, r1.description as desc
        LIMIT 5
        """, room_id=membership.room_id)
        contra_list = [r for r in contra]
        if contra_list:
            for r in contra_list:
                md += f"- **{r['source']}** contradicts **{r['target']}**: *{r['desc']}*\n"
        else:
            md += "No contradictions detected in the current knowledge graph.\n"
        md += "\n"
        
        # 3. Knowledge Gaps (Isolated Entities)
        md += "## 3. Top Knowledge Gaps\n"
        gaps = session.run("""
        MATCH (e:Entity {room_id: $room_id}) 
        WHERE NOT (e)-[]-(:Entity {room_id: $room_id}) 
        RETURN e.name as name, e.type as type 
        LIMIT 5
        """, room_id=membership.room_id)
        gaps_list = [r for r in gaps]
        if gaps_list:
            for g in gaps_list:
                md += f"- **{g['name']}** ({g['type']}) has no connections. Needs further research.\n"
        else:
            md += "No isolated knowledge gaps detected.\n"
            
    return md
